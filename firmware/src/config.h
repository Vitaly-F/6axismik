/*
 * Настройки прошивки. Всё, что обычно приходится менять, собрано здесь.
 * После изменения пересоберите и перепрошейте плату.
 */
#ifndef CONFIG_H
#define CONFIG_H

#define FW_VERSION "6axis-mik32 1.0"

/* Скорость связи с компьютером через USB-C (CH340N), бод */
#define UART_BAUD 115200

/* Частота генератора шагов, Гц.
 * Это же — максимальная скорость одной оси в шагах в секунду.
 * 25000 шаг/с при 1/8 шага (1600 шаг/об) = 15 об/с — с запасом для манипулятора. */
#define STEP_TICK_HZ 25000

/* Сколько отрезков движения помещается в очередь (обязательно степень двойки) */
#define QUEUE_LEN 32

/* Дополнительная выдержка импульса STEP (итераций пустого цикла).
 * 24 итерации дают импульс примерно 2-4 мкс: хватает и TMC2208/2209, и A4988 (нужно >= 1 мкс). */
#define STEP_PULSE_LOOPS 24

/* Инверсия направления. Бит 0 = ось 1, ..., бит 5 = ось 6.
 * Если ось крутится не в ту сторону — поставьте её бит в 1 (или поменяйте местами провода одной обмотки). */
#define DIR_INVERT_MASK 0x00

/* Концевики. Бит 0 = ось 1, ..., бит 5 = ось 6.
 * LIMIT_ENABLE_MASK      — какие концевики проверять (0x3F — все шесть, 0x00 — ни одного).
 * LIMIT_ACTIVE_LOW_MASK  — у каких концевиков "нажат" = 0 В.
 *   Обычная кнопка, замыкающая сигнал на GND (нормально разомкнутая) — бит = 1.
 *   Нормально замкнутая кнопка или датчик, который при срабатывании выдаёт 1 — бит = 0.
 * Без подключённого концевика вход подтянут к 3,3 В — для "активного нуля" это "не нажат". */
#define LIMIT_ENABLE_MASK 0x3F
#define LIMIT_ACTIVE_LOW_MASK 0x3F

/* Как часто опрашивать концевики и аварийную кнопку, мс */
#define INPUT_POLL_MS 1

/* Проверять исправность цепочки входов: вход D7 у 74HC165 подключён к земле
 * и всегда должен читаться как 0. Если читается 1 — регистр или буфер не работает. */
#define CHECK_INPUT_CHAIN 1

/* Энкодеры MT6701 (SSI): проверять контрольную сумму CRC6 */
#define ENCODER_CHECK_CRC 1

/* Включить кэш внешней флеш (программа работает заметно быстрее).
 * Если после прошивки плата "молчит" — попробуйте поставить 0. */
#ifndef ENABLE_SPIFI_CACHE
#define ENABLE_SPIFI_CACHE 0  /* 0 — программу запускает загрузчик ELBEAR; с 1 МК зависает */
#endif

#endif
